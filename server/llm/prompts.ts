import type {
  RewriteAuditInput,
  RewritePromptInput,
  RewriteRepairInput,
} from './types.ts';

const TONE_INSTRUCTIONS: Record<RewritePromptInput['request']['tone'], string> = {
  neutral: 'Сохрани нейтральную, информационную подачу без эмоциональной окраски.',
  joyful:
    'Сделай подачу заметно более живой, светлой и энергичной: используй динамичный ритм, активные глаголы и воодушевляющую лексику. Не называй событие успешным, важным или хорошим, если этого нет в исходнике.',
  sad:
    'Сделай подачу заметно более тихой, задумчивой и меланхоличной: используй спокойный ритм и лексику с оттенком сожаления. Не добавляй потери, ущерб или трагические последствия, которых нет в исходнике.',
  ironic:
    'Сделай подачу заметно ироничной и остроумной: используй легкий контраст, неожиданную формулировку или мягкую риторическую улыбку. Не добавляй новые факты, обвинения или злой сарказм.',
  custom:
    'Следуй пользовательскому стилю заметно, но только в части подачи, ритма, лексики и эмоций.',
};

function factsJson(input: RewritePromptInput): string {
  return JSON.stringify(input.facts, null, 2);
}

export function rewriteSystemPrompt(): string {
  return `Ты — русский редактор новостей. Сделай полноценный стилистический рерайт короткой новости, сохранив ее фактический смысл.

КРИТИЧЕСКИЕ ОГРАНИЧЕНИЯ:
- Не добавляй факты, которых нет в исходном тексте.
- Не удаляй и не меняй числа, даты, суммы, места, ссылки и цитаты.
- Имена и другие сущности можно грамматически склонять, но нельзя заменять другой сущностью или терять связь с исходным утверждением.
- Не превращай предположение в факт и факт в предположение.
- Не придумывай последствия, оценки как новые факты, контекст и источники.
- Сохраняй смысл каждого утверждения.
- Эмоциональные и риторические слова разрешены только как стилистическая подача, а не как новые проверяемые утверждения.
- Для режима не neutral результат должен заметно отличаться от исходника по синтаксису, ритму и лексике. Не возвращай исходный текст дословно, если это не требуется сохранением фактов.
- Защищенные числа, даты, ссылки и цитаты копируй в том же написании, чтобы они прошли автоматическую проверку.
- Ответ должен быть только JSON с ключами rewrittenTitle и rewrittenSummary.
- Не используй Markdown и не оборачивай JSON в кодовый блок.`;
}

export function rewriteUserPrompt(input: RewritePromptInput): string {
  const customStyle = input.request.customStyle
    ? `\nПользовательский стиль: ${input.request.customStyle}`
    : '';

  return `Исходный заголовок:
${input.article.title}

Исходный анонс:
${input.article.summary}

Выбранный режим: ${input.request.tone}.
${TONE_INSTRUCTIONS[input.request.tone]}${customStyle}

Защищенные факты. Числа, даты, ссылки и цитаты должны сохраниться в исходном написании; сущности и утверждения должны остаться теми же по смыслу:
${factsJson(input)}

Сначала сохрани все защищенные факты, затем измени подачу. Для режима не neutral не копируй исходные предложения без стилистической переработки.

Верни JSON строго такого вида:
{"rewrittenTitle":"...","rewrittenSummary":"..."}`;
}

export function auditSystemPrompt(): string {
  return `Ты — строгий факт-чекер русскоязычных новостных рерайтов.

Сравни исходный текст и рерайт. Проверь:
- не исчезли ли утверждения;
- не появились ли новые утверждения;
- не изменились ли имена, числа, даты, суммы, места, ссылки, цитаты;
- не изменились ли причинность, модальность и степень уверенности.

Не считай проблемой перефразирование, изменение порядка слов, пунктуации, длины фраз,
грамматического падежа сущностей или эмоциональные слова, которые не добавляют нового
проверяемого утверждения. Если факты и утверждения эквивалентны, верни passed=true.
Указывай проблему только при реальном добавлении, пропуске или изменении смысла.

Ответь только JSON:
{"passed":true,"issues":[]}
или
{"passed":false,"issues":["конкретная проблема"]}.
Если сомневаешься, укажи проблему в issues.`;
}

export function auditUserPrompt(input: RewriteAuditInput): string {
  return `ИСХОДНЫЙ ТЕКСТ:
Заголовок: ${input.article.title}
Анонс: ${input.article.summary}

РЕРАЙТ:
Заголовок: ${input.draft.rewrittenTitle}
Анонс: ${input.draft.rewrittenSummary}

ЗАЩИЩЕННЫЕ ФАКТЫ:
${JSON.stringify(input.facts, null, 2)}`;
}

export function repairSystemPrompt(): string {
  return `${rewriteSystemPrompt()}

Предыдущий вариант не прошел проверку фактов. Исправь только перечисленные проблемы,
но обязательно сохрани выбранную тональность и уже сделанную стилистическую переработку.
Не возвращай нейтральный или дословный исходный текст только из-за осторожности.
Если проблема сформулирована неоднозначно, сохраняй исходный защищенный факт и меняй
только спорный фрагмент.`;
}

export function repairUserPrompt(input: RewriteRepairInput): string {
  return `${rewriteUserPrompt(input)}

Предыдущий вариант:
${JSON.stringify(input.draft, null, 2)}

Проблемы проверки:
${input.issues.map((issue) => `- ${issue}`).join('\n')}`;
}
